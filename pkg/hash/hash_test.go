package hash_test

import (
	"testing"

	"github.com/Panterrich/MetricCollector/pkg/hash"
	"github.com/stretchr/testify/assert"
)

func TestMessage(t *testing.T) {
	tests := []struct {
		name     string
		data     []byte
		key      []byte
		expected []byte
	}{
		{
			name: "Valid data",
			data: []byte("test data"),
			key:  []byte("secret key"),
			expected: []byte{
				0xd5, 0x1c, 0x42, 0x89, 0xe6, 0xee, 0xa4, 0x9d, 0xb0, 0x09, 0x25, 0xbb, 0x7a, 0x94, 0x8d, 0x31,
				0x30, 0x95, 0x50, 0x04, 0x0f, 0x88, 0xbc, 0x4a, 0xba, 0x39, 0xbb, 0x31, 0x07, 0xc0, 0x71, 0xbe},
		},
		{
			name: "Empty data",
			data: []byte{},
			key:  []byte("secret key"),
			expected: []byte{
				0xdd, 0xfa, 0x24, 0x83, 0x36, 0x1f, 0xb3, 0x52, 0x02, 0x68, 0x95, 0x47, 0xae, 0x9d, 0xab, 0x34,
				0xaa, 0x34, 0xdc, 0xa4, 0x8c, 0xb3, 0xcb, 0x86, 0x11, 0xf6, 0x98, 0x2f, 0xdf, 0x80, 0x88, 0xa0},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := hash.Message(tt.data, tt.key)
			assert.NoError(t, err)
			assert.Equal(t, tt.expected, got)
		})
	}
}

func TestCheckMessage(t *testing.T) {
	tests := []struct {
		name           string
		data           []byte
		key            []byte
		expectedHash   []byte
		wantMatch      bool
		expectedResult bool
	}{
		{
			name: "Matching hashes",
			data: []byte("test data"),
			key:  []byte("secret key"),
			expectedHash: []byte{
				0xd5, 0x1c, 0x42, 0x89, 0xe6, 0xee, 0xa4, 0x9d, 0xb0, 0x09, 0x25, 0xbb, 0x7a, 0x94, 0x8d, 0x31,
				0x30, 0x95, 0x50, 0x04, 0x0f, 0x88, 0xbc, 0x4a, 0xba, 0x39, 0xbb, 0x31, 0x07, 0xc0, 0x71, 0xbe},
			wantMatch:      true,
			expectedResult: true,
		},
		{
			name: "Non-matching hashes",
			data: []byte("different data"),
			key:  []byte("secret key"),
			expectedHash: []byte{
				0x6b, 0xe5, 0x4d, 0xb7, 0xd3, 0x2c, 0xc8, 0xda, 0xa9, 0x3a, 0xee, 0x6b, 0x12, 0x19, 0xda, 0x47,
				0x71, 0xde, 0x84, 0x1e, 0x58, 0xdc, 0xad, 0x67, 0x46, 0xbe, 0xaf, 0x98, 0x61, 0xf2, 0x28, 0xff},
			wantMatch:      false,
			expectedResult: false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			match, err := hash.CheckMessage(tt.data, tt.key, tt.expectedHash)
			assert.NoError(t, err)
			assert.Equal(t, tt.expectedResult, match)
		})
	}
}
